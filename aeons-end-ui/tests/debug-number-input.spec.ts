import { test, expect } from '@playwright/test'

test('Debug number controls reveal on hover or focus and update their values', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: 'Start Game' }).click()
  await page.keyboard.press('Control+d')

  const field = page.locator('.debug-number-field').filter({ has: page.getByRole('spinbutton', { name: /Aether for/ }) }).first()
  const input = field.getByRole('spinbutton')
  const steps = field.locator('.debug-number-steps')
  await expect(input).toHaveCSS('width', '58px')
  await expect(steps).toHaveCSS('opacity', '0')

  await field.hover()
  await expect(steps).toHaveCSS('opacity', '1')
  const colors = await field.locator('.debug-number-step.up').evaluate(button => ({
    actual: getComputedStyle(button).color,
    expected: getComputedStyle(document.documentElement).getPropertyValue('--muted').trim(),
  }))
  expect(colors.actual).toBe('rgb(139, 147, 167)')
  expect(colors.expected).toBe('#8b93a7')

  const before = Number(await input.inputValue())
  await field.getByRole('button', { name: /Increase Aether for/ }).click()
  await expect(input).toHaveValue(String(before + 1))

  await page.mouse.move(0, 0)
  await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur())
  await expect(steps).toHaveCSS('opacity', '0')
  await input.focus()
  await expect(steps).toHaveCSS('opacity', '1')
})

test('Debug Pulse token control enforces the five-token limit', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: 'Start Game' }).click()
  await page.keyboard.press('Control+d')

  const input = page.getByRole('spinbutton', { name: /Pulse tokens for/ }).first()
  await expect(input).toHaveAttribute('min', '0')
  await expect(input).toHaveAttribute('max', '5')
  const statRow = input.locator('xpath=../../..')
  const statFieldTops = await statRow.locator('.debug-stat-field').evaluateAll(fields =>
    fields.map(field => field.getBoundingClientRect().top),
  )
  expect(Math.max(...statFieldTops) - Math.min(...statFieldTops)).toBeLessThan(1)

  await input.fill('8')
  await input.evaluate(element => (element as HTMLInputElement).blur())
  await expect(input).toHaveValue('5')

  await input.locator('..').hover()
  await input.locator('..').getByRole('button', { name: /Increase Pulse tokens for/ }).click()
  await expect(input).toHaveValue('5')
})

test('Debug deck order editor moves cards within a selected player deck', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: 'Start Game' }).click()
  await page.keyboard.press('Control+d')

  const stateField = page.locator('.debug-panel textarea')
  await page.getByRole('button', { name: 'Load Current', exact: true }).click()
  const debugState = JSON.parse(await stateField.inputValue())
  debugState.game.players[0].deck = ['crystal', 'spark', 'jade']
  await stateField.fill(JSON.stringify(debugState))
  await page.getByRole('button', { name: 'Apply', exact: true }).click()

  await expect(page.getByRole('checkbox', { name: 'Enable deck order editing' })).toHaveCount(0)
  await expect(page.locator('.debug-deck-order-modal')).toHaveCount(0)
  const deckPlayer = page.getByLabel('Deck order player')
  const editButton = page.getByRole('button', { name: 'Edit Deck Order', exact: true })
  await deckPlayer.selectOption(debugState.game.players[0].id)
  const selectBox = await deckPlayer.boundingBox()
  const buttonBox = await editButton.boundingBox()
  expect(selectBox).not.toBeNull()
  expect(buttonBox).not.toBeNull()
  expect(Math.abs(selectBox!.height - buttonBox!.height)).toBeLessThan(1)
  expect(buttonBox!.x - (selectBox!.x + selectBox!.width)).toBeGreaterThanOrEqual(5)
  expect(buttonBox!.x - (selectBox!.x + selectBox!.width)).toBeLessThan(10)
  await editButton.click()
  const modal = page.locator('.debug-deck-order-modal')
  await expect(modal).toBeVisible()
  const cards = modal.locator('.debug-deck-order-card')
  await expect(cards).toHaveCount(3)
  await expect(modal.getByRole('button', { name: /Move .* (up|down)/ })).toHaveCount(0)
  const firstCard = cards.first()
  const secondCard = cards.nth(1)
  const firstName = await firstCard.locator('img').getAttribute('alt')
  const secondName = await secondCard.locator('img').getAttribute('alt')
  expect(firstName).not.toBe(secondName)
  await expect(firstCard).not.toHaveAttribute('draggable', 'true')

  const firstBox = await firstCard.boundingBox()
  const secondBox = await secondCard.boundingBox()
  expect(firstBox).not.toBeNull()
  expect(secondBox).not.toBeNull()
  await page.mouse.move(firstBox!.x + firstBox!.width / 2, firstBox!.y + firstBox!.height / 2)
  await page.mouse.down()
  await expect(firstCard).toHaveCSS('cursor', 'grabbing')
  await page.mouse.move(secondBox!.x + secondBox!.width * .8, secondBox!.y + secondBox!.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(cards.first().locator('img')).toHaveAttribute('alt', secondName ?? '')
  await expect(cards.nth(1).locator('img')).toHaveAttribute('alt', firstName ?? '')
  await page.waitForTimeout(250)

  // Leaving the modal while holding the pointer keeps the card attached and
  // moving; releasing it outside then ends the drag before the pointer returns.
  const heldSource = cards.last()
  const heldSourceName = await heldSource.locator('img').getAttribute('alt')
  const heldBox = await heldSource.boundingBox()
  expect(heldBox).not.toBeNull()
  await page.mouse.move(heldBox!.x + heldBox!.width / 2, heldBox!.y + heldBox!.height / 2)
  await page.mouse.down()
  await page.mouse.move(8, 8, { steps: 5 })
  await expect(modal.locator('.debug-deck-order-grid.is-dragging')).toHaveCount(1)

  const heldTargetBox = await cards.first().boundingBox()
  expect(heldTargetBox).not.toBeNull()
  await page.mouse.move(heldTargetBox!.x + heldTargetBox!.width * .2, heldTargetBox!.y + heldTargetBox!.height / 2, { steps: 8 })
  await expect(cards.first().locator('img')).toHaveAttribute('alt', heldSourceName ?? '')
  await expect(modal.locator('.debug-deck-order-grid.is-dragging')).toHaveCount(1)
  await page.mouse.up()
  await expect(modal.locator('.debug-deck-order-grid.is-dragging')).toHaveCount(0)
  await page.waitForTimeout(250)

  // Releasing outside the modal must stay released when the pointer returns.
  const reorderedFirst = cards.first()
  const reorderedBox = await reorderedFirst.boundingBox()
  expect(reorderedBox).not.toBeNull()
  await page.mouse.move(reorderedBox!.x + reorderedBox!.width / 2, reorderedBox!.y + reorderedBox!.height / 2)
  await page.mouse.down()
  await expect(reorderedFirst).toHaveCSS('cursor', 'grabbing')
  await page.mouse.move(8, 8, { steps: 5 })
  await expect(modal.locator('.debug-deck-order-grid.is-dragging')).toHaveCount(1)
  await page.mouse.up()
  await page.mouse.move(reorderedBox!.x + reorderedBox!.width / 2, reorderedBox!.y + reorderedBox!.height / 2)
  await expect(modal.locator('.debug-deck-order-grid.is-dragging')).toHaveCount(0)
  await expect(modal.locator('.debug-deck-order-card.is-dragging')).toHaveCount(0)
  await page.waitForTimeout(250)

  // The reorder control remains usable after an outside release.
  const nextSource = cards.nth(1)
  const nextTarget = cards.nth(2)
  const nextSourceBox = await nextSource.boundingBox()
  const nextTargetBox = await nextTarget.boundingBox()
  expect(nextSourceBox).not.toBeNull()
  expect(nextTargetBox).not.toBeNull()
  const beforeNextMove = await nextSource.locator('img').getAttribute('alt')
  await page.mouse.move(nextSourceBox!.x + nextSourceBox!.width / 2, nextSourceBox!.y + nextSourceBox!.height / 2)
  await page.mouse.down()
  await page.mouse.move(nextTargetBox!.x + nextTargetBox!.width * .8, nextTargetBox!.y + nextTargetBox!.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(cards.nth(2).locator('img')).toHaveAttribute('alt', beforeNextMove ?? '')
})

test('Debug text inputs suppress game shortcuts while Tab switches view and Escape closes Debug Tools', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: 'Start Game' }).click()
  await page.keyboard.press('Control+d')

  const jsonInput = page.locator('.debug-panel textarea')
  await jsonInput.fill('')
  await expect(jsonInput).toBeFocused()
  await page.keyboard.press('q')
  await page.keyboard.press('w')
  await expect(jsonInput).toHaveValue('qw')
  await expect(page.locator('.pile-modal')).toHaveCount(0)

  const selectedMage = page.locator('.char-btn.sel .cn')
  const initialMageName = await selectedMage.innerText()
  await page.keyboard.press('Tab')
  await expect(selectedMage).not.toHaveText(initialMageName)
  await expect(jsonInput).toBeFocused()

  const mageAfterTab = await selectedMage.innerText()
  await page.keyboard.press('2')
  await expect(jsonInput).toHaveValue('qw2')
  await expect(selectedMage).toHaveText(mageAfterTab)

  await page.keyboard.press('Control+d')
  await expect(page.locator('.debug-panel')).toBeVisible()
  await expect(jsonInput).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.locator('.debug-panel')).toHaveCount(0)
})
